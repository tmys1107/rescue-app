def next_qid(src, item_id):
    """その項目で未使用の最小番号を返す。決め打ちすると既存と衝突する
       （007 は既に q7 まであり、q6 を決め打ちして重複させた）"""
    used = set(int(n) for n in re.findall(r'"qid": "%s-q(\d+)"' % item_id, src))
    n = 1
    while n in used:
        n += 1
    return "%s-q%d" % (item_id, n)


def j(obj, indent):
    """既存の整形に合わせて JSON 断片を作る（配列は1要素1行）"""
    return json.dumps(obj, ensure_ascii=False, indent=2).replace("\n", "\n" + " " * indent)


def main():
    src = io.open(PATH, encoding="utf-8").read()
    if MARK in src or '"id": "028"' in src:
        print("既に取り込み済み。何もしない")
        return

    lines = src.split("\n")
    out = []
    cur = None
    added_notes = added_quiz = 0

    i = 0
    while i < len(lines):
        line = lines[i]
        m = re.match(r'^\s*"id": "(\d+)"', line)
        if m:
            cur = m.group(1)
        out.append(line)

        # "notes": [ の直後に挿し込む
        if cur in ADD_NOTES and re.match(r'^\s*"notes": \[\s*$', line):
            for v in ADD_NOTES[cur]:
                out.append('      %s,' % json.dumps(v, ensure_ascii=False))
                added_notes += 1

        # "quiz": [ の直後に挿し込む
        if cur in ADD_QUIZ and re.match(r'^\s*"quiz": \[\s*$', line):
            for q in ADD_QUIZ[cur]:
                q = dict(qid=next_qid(src, cur), **q)
                src += '"qid": "%s"' % q["qid"]      # 同じ項目に複数足すとき用
                out.append("      " + j(q, 6) + ",")
                added_quiz += 1
        i += 1

    s = "\n".join(out)

    # 末尾の ] の直前に新規項目を足す
    tail = s.rstrip()
    assert tail.endswith("]"), "末尾が ] でない"
    body = tail[:-1].rstrip()
    assert body.endswith("}"), "最後の項目が } で終わっていない"
    blocks = ",\n".join("  " + j(it, 2) for it in NEW)
    s = body + ",\n" + blocks + "\n]\n"

    io.open(PATH, "w", encoding="utf-8", newline="\n").write(s)

    items = json.load(io.open(PATH, encoding="utf-8"))
    print("知見 %d件 / 問題 %d問 を既存項目に追加" % (added_notes, added_quiz))
    print("新規 %d件を追加" % len(NEW))
    print()
    print("合計 %d件 / 問題 %d問" % (len(items), sum(len(x.get("quiz") or []) for x in items)))
    ids = [x["id"] for x in items]
    assert len(ids) == len(set(ids)), "idが重複している"
    qids = [q["qid"] for x in items for q in (x.get("quiz") or [])]
    assert len(qids) == len(set(qids)), "qidが重複している"
    print("id・qidの重複なし")


if __name__ == "__main__":
    main()
